import type { ModelReasoningEffort, Usage } from "@openai/codex-sdk";
import type { StageRecord, RoutingRecord } from '../core/orchestrator.js';
export type Effort = ModelReasoningEffort;
export type ModelOption = {
  model: string;
  efforts: Effort[];
  defaultEffort?: Effort;
  enabled?: boolean;
};
export type Route = { model?: string; effort?: Effort };
export type ManualWorkflow = {
  shape: "single" | "scout" | "plan" | "scout_plan" | "plan_execute" | "scout_plan_execute" | "plan_verify";
  routes: Partial<Record<"scout" | "plan" | "final", Route | "vex">>;
};
export type ApprovalMode = "full-access" | "request-approval" | "limited";
export type Task = { id: string; text: string; completed: boolean; source: "user" | "agent" };
export type TurnActivity = {
  category: "thinking" | "command" | "files" | "tool" | "search" | "plan";
  text: string;
  detail?: string;
  outcome?: "success" | "failure";
  durationMs?: number;
  tokens?: number;
};
export type ContextMeasurement = {
  tokens: number;
  windowTokens: number;
  model?: string;
};
export type Config = {
  models: ModelOption[];
  defaultRoute: Route;
  routingMode: "auto" | "manual";
  approvalMode?: ApprovalMode;
  trustedFolders?: string[];
  skillFolder?: string | null;
  disabledSkills?: string[];
};
export type TurnSummary = {
  prompt: string;
  displayPrompt?: string;
  intent?: "verify_plan" | "execute_plan";
  result: string;
  at: string;
  route?: Route;
  routeNote?: string;
  systemMessages?: string[];
  activities?: TurnActivity[];
  questions?: { question: string; answer: string }[];
  durationMs?: number;
  artifacts?: string[];
  usage?: Usage;
  stages?: StageRecord[];
  routing?: RoutingRecord[];
  estimatedCostUsd?: number;
  failed?: boolean;
  cancelled?: boolean;
};
export type CompactionRecord = {
  at: string;
  threadId: string;
  route: Route;
  durationMs: number;
  outcome: "completed" | "failed" | "cancelled";
  usage?: Usage;
  estimatedCostUsd?: number;
  error?: string;
};
export type CheckpointNote = {
  complete: true;
  goal: string;
  constraints: string[];
  findings: { detail: string; file?: string }[];
  changes: { detail: string; file?: string }[];
  checks: { command: string; outcome: string }[];
  unfinished: string[];
  questions: string[];
  risks: string[];
};
export type CheckpointRecord = {
  createdAt: string;
  sourceTurnAt: string;
  threadId: string;
  route: Route;
  note: CheckpointNote;
  durationMs: number;
  usage?: Usage;
  estimatedCostUsd?: number;
};
export type CheckpointGeneration = {
  at: string;
  sourceTurnAt: string;
  threadId: string;
  route: Route;
  durationMs: number;
  outcome: "valid" | "invalid" | "failed" | "cancelled";
  usage?: Usage;
  estimatedCostUsd?: number;
  error?: string;
};
export type SessionKind = "normal" | "planning";
export type Session = {
  id: string;
  kind?: SessionKind;
  plan?: string;
  planArtifact?: string;
  title?: string;
  projectPath: string;
  threadId?: string;
  threadTurnCount?: number;
  contextByThread?: Record<string, ContextMeasurement>;
  createdAt: string;
  updatedAt: string;
  routingMode: "auto" | "manual";
  route: Route;
  manualWorkflow?: ManualWorkflow;
  activeSkills?: string[];
  tasks?: Task[];
  activeTask?: { originalRequest: string; instructions: string[]; latestOutcome?: string; failed?: boolean };
  deferredTurn?: { prompt: string; retryAt: string; attempt: number; reason?: "usage" | "network" | "capacity"; intent?: "verify_plan" | "execute_plan"; displayPrompt?: string };
  skillOptions?: Record<string, string>;
  turns: TurnSummary[];
  compactions?: CompactionRecord[];
  checkpoint?: CheckpointRecord;
  checkpointGenerations?: CheckpointGeneration[];
};
export type Notice = (message: string) => void;
